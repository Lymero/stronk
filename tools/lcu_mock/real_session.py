"""A champion select session over the real data, for `just e2e-real` (ADR-061).

    real_session.py --data runs/real/data --out <file> [--static <crawl>/static/<patch>.json.gz]
        [--picks LeeSin/JUNGLE,Jinx/BOTTOM,...]

One step per pick, each the local player locked in on that champion and role, after a lobby
step. The champions' ids and names come from the crawl's static data (by default the first
`runs/corpus*/*/static/<patch>.json.gz` for the data's patch); the session also gives
lcu-mock every item's name from it (`game_data`), so the board shows names rather than ids.
Without `--picks`: one popular champion per role, and the champion and role with the fewest
games in the data, to see a sparse board too.
"""

from __future__ import annotations

import argparse
import gzip
import json
import re
import sys
from pathlib import Path
from typing import Any

ITEMS = "/lol-game-data/assets/v1/items.json"
POSITIONS = {
    "TOP": "top",
    "JUNGLE": "jungle",
    "MIDDLE": "middle",
    "BOTTOM": "bottom",
    "UTILITY": "utility",
}
POPULAR = ["LeeSin/JUNGLE", "Jinx/BOTTOM", "Thresh/UTILITY", "Ahri/MIDDLE", "Darius/TOP"]
ALIASES = {"MonkeyKing": "Wukong"}
"""Data folder names that aren't the champion's name without spaces and punctuation."""


def flat(name: str) -> str:
    return re.sub(r"[^a-z]", "", name.lower())


def builds(data: Path) -> Path:
    """The newest patch's `all/master_plus` folder of the data."""
    patches = sorted(p for p in data.iterdir() if p.is_dir())
    if not patches:
        raise ValueError(f"{data}: no patch folder")
    return patches[-1] / "all" / "master_plus"


def find_static(patch: str) -> Path:
    """A crawl's static data for `patch` among the fetched and built corpora."""
    root = Path(__file__).resolve().parents[2]
    found = sorted(root.glob(f"runs/corpus*/*/static/{patch}.json.gz"))
    if not found:
        raise ValueError(
            f"no static data for {patch} under runs/corpus*/: `just corpus` or pass --static"
        )
    return found[0]


def sparsest(folder: Path) -> str:
    """The champion and role with the fewest games."""
    games = {
        f"{f.parent.name}/{f.stem}": json.loads(f.read_text())["games"]
        for f in folder.glob("*/*.json")
    }
    return min(games, key=lambda k: (games[k], k))


def champion(alias: str, champions: dict[str, dict[str, Any]]) -> dict[str, Any]:
    """The client's champion summary for a data folder name, from the static data."""
    wanted = flat(ALIASES.get(alias, alias))
    for c in champions.values():
        if flat(c["name"]) == wanted or flat(c["name"]).startswith(wanted):
            return {"id": c["champion_id"], "alias": alias, "name": c["name"]}
    raise ValueError(f"{alias}: not in the static data")


def session(data: Path, static: Path | None, picks: list[str] | None) -> dict[str, Any]:
    folder = builds(data)
    static = static or find_static(folder.parents[1].name)
    chosen = picks or [*POPULAR, sparsest(folder)]
    with gzip.open(static) as f:
        doc: dict[str, Any] = json.loads(f.read())
    steps: list[dict[str, Any]] = [{"name": "lobby", "session": None}]
    champions: dict[int, dict[str, Any]] = {}
    for pick in chosen:
        alias, role = pick.split("/")
        if not (folder / alias / f"{role}.json").is_file():
            raise ValueError(f"{pick}: no build in {folder}")
        c = champion(alias, doc["champions"])
        champions[c["id"]] = c
        steps.append({
            "name": f"locked {alias} {role}",
            "session": {
                "localPlayerCellId": 0,
                "timer": {"phase": "FINALIZATION", "adjustedTimeLeftInPhase": 30000},
                "myTeam": [{"cellId": 0, "championId": c["id"], "championPickIntent": 0,
                            "assignedPosition": POSITIONS[role]}],
                "actions": [[{"id": 1, "actorCellId": 0, "championId": c["id"], "completed": True,
                              "isInProgress": False, "type": "pick"}]],
            },
        })  # fmt: skip
    mock: dict[str, Any] = json.loads(Path(__file__).with_name("game_data.json").read_text())
    items = {i["id"]: i for i in mock[ITEMS]}
    for item in doc["items"].values():
        items.setdefault(item["item_id"], {
            "id": item["item_id"],
            "name": item["name"],
            "iconPath": f"/lol-game-data/assets/ASSETS/Items/Icons2D/{item['item_id']}.png",
        })  # fmt: skip
    return {
        "source": f"Generated by real_session.py from {data} and {static.name}; not a recording.",
        "picks": chosen,
        "champions": [{"id": -1, "alias": "None", "name": "None"}, *champions.values()],
        "game_data": {ITEMS: sorted(items.values(), key=lambda i: i["id"])},
        "steps": steps,
    }


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="A champion select session over the real data")
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--static", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--picks", help="Champion/ROLE, comma-separated")
    args = parser.parse_args(argv)
    try:
        doc = session(args.data, args.static, args.picks.split(",") if args.picks else None)
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as e:
        print(f"real-session: {e}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(doc, indent=1))
    print(f"real-session: {', '.join(doc['picks'])} -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
