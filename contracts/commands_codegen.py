"""Generate the UI's command types from the core's registry (ADR-053).

Usage:
    python contracts/commands_codegen.py           # write app/ui/src/lib/backend/commands.ts
    python contracts/commands_codegen.py --check   # fail if it is stale

`stronk-core schema` prints every command's params and result as one JSON Schema; json2ts (the
tool contracts/codegen.py uses) turns it into TypeScript. Needs cargo and json2ts (pnpm).
"""

from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "app/ui/src/lib/backend/commands.ts"
HEADER = (
    "/* Generated by contracts/commands_codegen.py from `stronk-core schema`. Do not edit; run"
    " `just gen`. */"
)
# `build.get` returns the contract's build file, typed by the contract's own generated types.
IMPORTS = 'import type { BuildV1 } from "@stronk/contracts";\n\n'


def run(*args: str | Path) -> bytes:
    try:
        result = subprocess.run([str(a) for a in args], check=False, cwd=ROOT, capture_output=True)
    except FileNotFoundError:
        raise SystemExit(f"commands codegen: `{args[0]}` not found; run `just setup`") from None
    if result.returncode != 0:
        sys.stderr.write(
            result.stdout.decode(errors="replace") + result.stderr.decode(errors="replace")
        )
        raise SystemExit(f"commands codegen: command failed: {' '.join(str(a) for a in args)}")
    return result.stdout


def generate() -> str:
    schema = run(
        "cargo", "run", "--quiet", "--locked",
        "--manifest-path", ROOT / "app/core/Cargo.toml",
        "-p", "stronk-cli", "--", "schema",
    )  # fmt: skip
    json2ts = ROOT / "node_modules/.bin" / ("json2ts.CMD" if sys.platform == "win32" else "json2ts")
    with tempfile.TemporaryDirectory(prefix="stronk-commands-") as tmp:
        source, target = Path(tmp) / "commands.schema.json", Path(tmp) / "commands.ts"
        source.write_bytes(schema)
        run(
            json2ts,
            "--input", source,
            "--output", target,
            "--additionalProperties", "false",
            "--unreachableDefinitions",
            "--bannerComment", HEADER,
        )  # fmt: skip
        text = target.read_text(encoding="utf-8").replace("\r\n", "\n")
    banner, _, body = text.partition("\n")
    return f"{banner}\n\n{IMPORTS}{body.lstrip()}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="fail if commands.ts is stale")
    args = parser.parse_args()
    fresh = generate()
    rel = TARGET.relative_to(ROOT)
    if args.check:
        old = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if old != fresh:
            diff = difflib.unified_diff(
                old.splitlines(keepends=True), fresh.splitlines(keepends=True), str(rel), "fresh"
            )
            sys.stderr.write(
                "".join(diff) + f"\ncommands codegen: {rel} is stale; run `just gen`\n"
            )
            return 1
        print(f"commands codegen: {rel} up to date")
        return 0
    TARGET.write_text(fresh, encoding="utf-8", newline="\n")
    print(f"commands codegen: wrote {rel}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
