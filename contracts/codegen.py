"""Generate Python, TypeScript and Rust types from contracts/schemas/.

Usage:
    python contracts/codegen.py           # write contracts/generated/
    python contracts/codegen.py --check   # fail if contracts/generated/ is stale

Needs datamodel-codegen (uv dev group), json2ts (pnpm), cargo-typify and rustfmt (mise).
"""

from __future__ import annotations

import argparse
import difflib
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

CONTRACTS = Path(__file__).resolve().parent
ROOT = CONTRACTS.parent
SCHEMAS = CONTRACTS / "schemas"
GENERATED = CONTRACTS / "generated"

PY_DIR = Path("python/src/stronk_contracts")
TS_DIR = Path("ts/src")
RS_DIR = Path("rust/src")

HEADER = "Generated by contracts/codegen.py from contracts/schemas/. Do not edit; run `just gen`."


@dataclass(frozen=True)
class Schema:
    path: Path

    @property
    def module(self) -> str:
        """`build.v1.schema.json` -> `build_v1`."""
        return self.path.name.removesuffix(".schema.json").replace(".", "_").replace("-", "_")


def run(*args: str | Path) -> None:
    try:
        result = subprocess.run(
            [str(a) for a in args], check=False, cwd=ROOT, capture_output=True, text=True
        )
    except FileNotFoundError:
        raise SystemExit(
            f"codegen: `{args[0]}` not found. Run `mise install`, then activate mise in your "
            "shell or prefix the command with `mise exec --`."
        ) from None
    if result.returncode != 0:
        sys.stderr.write(result.stdout + result.stderr)
        raise SystemExit(f"codegen: command failed: {' '.join(str(a) for a in args)}")


def gen_python(schema: Schema, out: Path) -> None:
    target = out / PY_DIR / f"{schema.module}.py"
    run(
        "datamodel-codegen",
        "--input", schema.path,
        "--input-file-type", "jsonschema",
        "--output-model-type", "pydantic_v2.BaseModel",
        "--output", target,
        "--target-python-version", "3.13",
        "--formatters", "ruff-format",
        "--custom-file-header", f"# {HEADER}",
        "--use-standard-collections",
        "--use-union-operator",
        "--use-annotated",
        "--field-constraints",
        "--snake-case-field",
        "--use-double-quotes",
        "--enum-field-as-literal", "all",
        "--use-schema-description",
        "--use-field-description",
        "--extra-fields", "forbid",
        "--disable-timestamp",
    )  # fmt: skip


def gen_typescript(schema: Schema, out: Path) -> None:
    target = out / TS_DIR / f"{schema.module}.ts"
    run(
        ROOT / "node_modules/.bin/json2ts",
        "--input", schema.path,
        "--output", target,
        "--additionalProperties", "false",
        "--bannerComment", f"/* {HEADER} */",
    )  # fmt: skip


def gen_rust(schema: Schema, out: Path) -> None:
    target = out / RS_DIR / f"{schema.module}.rs"
    run("cargo", "typify", "--no-builder", schema.path, "--output", target)


def gen_indexes(schemas: list[Schema], out: Path) -> None:
    modules = [s.module for s in schemas]
    (out / PY_DIR / "__init__.py").write_text(
        f'"""{HEADER}"""\n\nfrom . import {", ".join(modules)}\n\n__all__ = {modules!r}\n'.replace(
            "'", '"'
        )
    )
    (out / TS_DIR / "index.ts").write_text(
        f"/* {HEADER} */\n\n"
        + "".join(f'export type * as {pascal(m)} from "./{m}.ts";\n' for m in modules)
    )
    # Typify unwraps regexes compiled from constant schema patterns; contract tests parse a
    # value through every pattern, so a bad pattern fails CI, never a user's app.
    (out / RS_DIR / "lib.rs").write_text(
        f"//! {HEADER}\n\n"
        + "".join(f"#[allow(clippy::unwrap_used, clippy::all)]\npub mod {m};\n" for m in modules)
    )


def pascal(module: str) -> str:
    return "".join(part.capitalize() for part in module.split("_"))


def generate(out: Path) -> None:
    schemas = [Schema(p) for p in sorted(SCHEMAS.glob("*.schema.json"))]
    for d in (PY_DIR, TS_DIR, RS_DIR):
        (out / d).mkdir(parents=True, exist_ok=True)
    for schema in schemas:
        gen_python(schema, out)
        gen_typescript(schema, out)
        gen_rust(schema, out)
    gen_indexes(schemas, out)
    run("rustfmt", "--edition", "2024", *sorted((out / RS_DIR).glob("*.rs")))


def generated_files(root: Path) -> set[Path]:
    files: set[Path] = set()
    for d, pattern in ((PY_DIR, "*.py"), (TS_DIR, "*.ts"), (RS_DIR, "*.rs")):
        files |= {p.relative_to(root) for p in (root / d).glob(pattern)}
    return files


def check(fresh: Path) -> int:
    expected, actual = generated_files(fresh), generated_files(GENERATED)
    problems: list[str] = []
    for rel in sorted(expected | actual):
        if rel not in actual:
            problems.append(f"missing: contracts/generated/{rel}")
        elif rel not in expected:
            problems.append(f"stale: contracts/generated/{rel}")
        else:
            new, old = (fresh / rel).read_text(), (GENERATED / rel).read_text()
            if new != old:
                diff = difflib.unified_diff(
                    old.splitlines(keepends=True), new.splitlines(keepends=True), str(rel), "fresh"
                )
                problems.append("".join(diff))
    if problems:
        sys.stderr.write(
            "\n".join(problems) + "\ncodegen: generated types are stale; run `just gen`\n"
        )
        return 1
    print(f"codegen: {len(expected)} generated files up to date")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="stronk-codegen-") as tmp:
        fresh = Path(tmp)
        generate(fresh)
        if args.check:
            return check(fresh)
        for rel in generated_files(GENERATED) - generated_files(fresh):
            (GENERATED / rel).unlink()
        for rel in generated_files(fresh):
            (GENERATED / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(fresh / rel, GENERATED / rel)
        print(f"codegen: wrote {len(generated_files(fresh))} files to contracts/generated/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
